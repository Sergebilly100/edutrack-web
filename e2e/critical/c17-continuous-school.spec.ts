async function workbook(headers: string[], rows: Array<Array<string | number>>) {
  const book = new ExcelJS.Workbook()
  const sheet = book.addWorksheet("Données")
  sheet.addRow(headers)
  for (const row of rows) sheet.addRow(row)
  return { name: "c17.xlsx", mimeType: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", buffer: Buffer.from(await book.xlsx.writeBuffer()) }
}

